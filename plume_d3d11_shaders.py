"""Compiles the D3D11 backend's internal shaders into plume_d3d11_shaders.h.

Run on Windows after editing SOURCE: py -3 plume_d3d11_shaders.py
It uses the system d3dcompiler_47.dll, so no SDK is needed.
"""
import ctypes
import pathlib

SOURCE = r"""
// Rect clears and component swizzles, which D3D11 has no native call for.
cbuffer Internal : register(b0) {
    float4 color;
    float depth;
    uint slice;
    uint mip;
    uint pad;
    uint4 mapping; // RenderSwizzle per output component.
};

// One triangle covering the target; the scissor rect limits it.
float4 FullscreenVS(uint id : SV_VertexID) : SV_Position {
    float2 uv = float2((id << 1) & 2, id & 2);
    return float4(uv * float2(2.0, -2.0) + float2(-1.0, 1.0), depth, 1.0);
}

float4 ClearPS() : SV_Target0 {
    return color;
}

Texture2DArray<float4> source : register(t0);

float component(float4 c, uint swizzle, uint index) {
    if (swizzle == 0) return c[index];
    if (swizzle == 1) return 0.0;
    if (swizzle == 2) return 1.0;
    return c[swizzle - 3];
}

float4 SwizzlePS(float4 position : SV_Position) : SV_Target0 {
    float4 c = source.Load(int4(int2(position.xy), slice, mip));
    return float4(component(c, mapping.x, 0), component(c, mapping.y, 1),
        component(c, mapping.z, 2), component(c, mapping.w, 3));
}
"""

ENTRIES = (("FullscreenVS", "vs_5_0"), ("ClearPS", "ps_5_0"), ("SwizzlePS", "ps_5_0"))


def blob_bytes(blob):
    vtable = ctypes.cast(blob, ctypes.POINTER(ctypes.POINTER(ctypes.c_void_p))).contents
    pointer = ctypes.WINFUNCTYPE(ctypes.c_void_p, ctypes.c_void_p)(vtable[3])(blob)
    size = ctypes.WINFUNCTYPE(ctypes.c_size_t, ctypes.c_void_p)(vtable[4])(blob)
    return ctypes.string_at(pointer, size)


def compile_entry(entry, profile):
    compiler = ctypes.WinDLL("d3dcompiler_47.dll")
    code, errors = ctypes.c_void_p(), ctypes.c_void_p()
    source = SOURCE.encode()
    status = compiler.D3DCompile(source, len(source), b"plume_d3d11_shaders.hlsl", None, None,
        entry.encode(), profile.encode(), 1 << 15, 0, ctypes.byref(code), ctypes.byref(errors))
    if status != 0:
        raise SystemExit(blob_bytes(errors).decode(errors="replace") if errors.value else hex(status))
    return blob_bytes(code)


lines = ["// Generated by plume_d3d11_shaders.py. Do not edit.", "#pragma once", "#include <cstdint>", ""]
for entry, profile in ENTRIES:
    data = compile_entry(entry, profile)
    lines.append(f"static const uint8_t D3D11{entry}Bytes[] = {{")
    for start in range(0, len(data), 16):
        lines.append("    " + ", ".join(f"0x{byte:02X}" for byte in data[start:start + 16]) + ",")
    lines.append("};")
    lines.append("")
pathlib.Path(__file__).with_name("plume_d3d11_shaders.h").write_text("\n".join(lines), encoding="ascii")
